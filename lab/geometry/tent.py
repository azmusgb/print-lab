"""Parametric 15° Leaned-Pair Tent Stabilizer Generator.

Creates a braced triangular pair of hex tiles leaned 15° back-to-back,
joined by self-supporting internal fin ribs and a ridge bar with break-away necks.
Eliminates upper-edge wobble and ensures all front facets face upwards (+7° to +24°).
"""
import math
import subprocess
from pathlib import Path


def generate_tent_scad(
    *,
    tile_width: float = 152.4,
    tile_height: float = 132.0,
    tile_thickness: float = 10.0,
    lean_deg: float = 15.0,
    fins: int = 3,
    fin_thickness: float = 1.2,
    neck_mm: float = 0.4,
    ridge_bar_mm: float = 8.0,
    source_model: str | None = None,
) -> str:
    """Generate clean OpenSCAD code for the 15° braced tent pair."""
    rad = math.radians(lean_deg)
    # Height of leaned tile
    leaned_height = round(tile_height * math.cos(rad), 2)
    # Base spread of the tent
    base_spread = round(2 * tile_height * math.sin(rad), 2)

    scad = f"""// Print Lab: 15° Leaned-Pair Tent Stabilizer
// Automatically generated by `lab tent`
// Base spread: {base_spread} mm, Leaned height: {leaned_height} mm

$fn = 60;

// Dimensions
tile_width = {tile_width:g};
tile_height = {tile_height:g};
tile_thickness = {tile_thickness:g};
lean_deg = {lean_deg:g};
fin_count = {fins};
fin_thickness = {fin_thickness:g};
neck_thickness = {neck_mm:g};
ridge_bar = {ridge_bar_mm:g};

module single_tile_placeholder() {{
    // Simplified hex tile profile for preview (replace with imported STL/3MF if available)
    linear_extrude(height=tile_thickness, center=true) {{
        polygon([
            [0, tile_height/2],
            [tile_width/2, tile_height/4],
            [tile_width/2, -tile_height/4],
            [0, -tile_height/2],
            [-tile_width/2, -tile_height/4],
            [-tile_width/2, tile_height/4]
        ]);
    }}
}}

module fin_brace(z_pos, span_width) {{
    // Triangular internal fin connecting the backs with a breakaway neck
    translate([0, 0, z_pos])
    difference() {{
        hull() {{
            translate([0, -span_width/2, 0]) cube([fin_thickness, 2, 8], center=true);
            translate([0, span_width/2, 0]) cube([fin_thickness, 2, 8], center=true);
        }}
        // Perforated breakaway notch near each tile back
        translate([0, -span_width/2 + 1, 0]) cube([fin_thickness + 0.2, neck_thickness, 10], center=true);
        translate([0, span_width/2 - 1, 0]) cube([fin_thickness + 0.2, neck_thickness, 10], center=true);
    }}
}}

module tent_pair() {{
    rad = lean_deg * PI / 180;
    z_offset = tile_height * cos(rad) / 2;
    y_spread = tile_height * sin(rad);

    // Front tile (leaned back)
    translate([0, -y_spread/2, z_offset])
    rotate([lean_deg, 0, 0])
    children(0);

    // Back tile (leaned back in opposite direction)
    translate([0, y_spread/2, z_offset])
    rotate([-lean_deg, 0, 180])
    children(0);

    // Ridge connector bar at top
    translate([0, 0, tile_height * cos(rad) - ridge_bar/2])
    cube([tile_width * 0.4, 2 * tile_thickness * sin(rad) + 2, ridge_bar], center=true);

    // Internal fin braces along the height
    for (i = [1 : fin_count]) {{
        h_ratio = i / (fin_count + 1);
        z_h = tile_height * cos(rad) * h_ratio;
        curr_span = y_spread * (1 - h_ratio);
        fin_brace(z_h, curr_span);
    }}
}}

// Assembly preview
tent_pair() single_tile_placeholder();
"""
    return scad


def write_tent_scad(out_path: Path | str, **kwargs) -> Path:
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    scad_code = generate_tent_scad(**kwargs)
    p.write_text(scad_code)
    return p


def render_tent_stl(scad_path: Path, stl_out: Path) -> Path:
    cmd = ["openscad", "-o", str(stl_out), str(scad_path)]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"OpenSCAD render failed: {res.stderr or res.stdout}")
    return stl_out

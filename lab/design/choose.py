"""Choosing a candidate: a design that passed the gate becomes a registered source through `lab variant add`, with
a params.json in the shape Send to lab writes (so everything that reads a source's parameters reads it) and a change
line naming the family, version, seed, design id and the parameters that differ from the family's defaults.

The candidate's model.stl is rebuilt from its family first and must match to 0.1% of volume: a family that has
changed since the run (a new version) can't register a model it no longer makes."""
import json
from pathlib import Path

from lab.design.family import design_id, resolve
from lab.design.gate import designs_dir
from lab.records.project import ProjectPaths


def find(paths: ProjectPaths, did: str) -> Path:
    """The candidate folder for a design id (or a unique prefix of one)."""
    hits = [p for p in designs_dir(paths).glob(f"*/{did}*") if (p / "gate.json").is_file()]
    if not hits:
        raise ValueError(f"No kept candidate {did} under {designs_dir(paths)}; the gallery lists them.")
    if len(hits) > 1:
        raise ValueError(f"{did} matches {', '.join(p.name for p in hits)}; give more of the id.")
    return hits[0]


def fusion_params(family, params: dict[str, float], seed: int, did: str) -> dict:
    """The design's parameters in Send to lab's shape, with what made it."""
    return {"document": f"{family.NAME} v{family.VERSION} seed {seed}", "family": family.NAME,
            "version": family.VERSION, "seed": seed, "design": did,
            "parameters": [{"name": q.name, "expression": f"{params[q.name]:g} {q.unit}".strip(),
                            "value": params[q.name], "unit": q.unit, "comment": q.meaning} for q in family.PARAMS]}


def change_line(family, params: dict[str, float], seed: int, did: str, base: str) -> str:
    default = resolve(family.PARAMS)
    diffs = [f"{q.name} {default[q.name]:g} → {params[q.name]:g} {q.unit}".rstrip() for q in family.PARAMS
             if abs(params[q.name] - default[q.name]) > 1e-9]
    layout = "Rift v6's facet layout" if seed == 0 else f"facet layout seed {seed}"
    return (f"generated by {family.NAME} v{family.VERSION} (design {did}): {layout}; "
            + ("; ".join(diffs) if diffs else "parameters at the family's defaults") + f"; settings from {base}")


def choose(paths: ProjectPaths, did: str, name: str | None = None, note: str | None = None) -> dict:
    """Register the candidate as sources/<name>.3mf; returns its sources.json entry."""
    import trimesh

    from lab.design.families import FAMILIES
    from lab.records.store import atomic_write_json
    from lab.variant import add_variant

    folder = find(paths, did)
    gate = json.loads((folder / "gate.json").read_text())
    if gate.get("dropped"):
        raise ValueError(f"{gate['id']} was dropped at the gate ({'; '.join(gate['dropped'])}); it can't be chosen.")
    family = FAMILIES.get(gate["family"])
    if family is None or family.VERSION != gate["version"]:
        raise ValueError(f"{gate['id']} was made by {gate['family']} v{gate['version']}, which this lab no longer "
                         "has; make it again with the current family.")
    params, seed = resolve(family.PARAMS, gate["params"]), gate["seed"]
    if design_id(family.NAME, family.VERSION, params, seed) != gate["id"]:
        raise ValueError(f"{folder}/gate.json doesn't match its own id; make the candidate again.")
    stl = folder / "model.stl"
    rebuilt = family.build(params, seed).volume
    made = abs(trimesh.load(stl, force="mesh").volume)
    if abs(made - rebuilt) > 0.001 * rebuilt:
        raise ValueError(f"{stl} ({made:.1f} mm³) no longer matches what {family.NAME} builds ({rebuilt:.1f} mm³); "
                         "make the candidate again.")
    side = folder / "choose.params.json"
    atomic_write_json(side, fusion_params(family, params, seed, gate["id"]))
    return add_variant(paths, mesh=stl, base=gate["base"], name=name or f"{family.NAME}_s{seed}_{gate['id']}",
                       params=side, note=note, change=change_line(family, params, seed, gate["id"], gate["base"]))
